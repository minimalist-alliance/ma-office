// Writes dev/tokens.json: the theme tokens the harness hands the view, exactly as the Desk app's host does
// (`web/src/deskapps/host/tokens.ts` on sub/apps-host: the office's semantic tokens by dotted name, `theme` and `font`, with
// an app's own ink put over its window, sunken and accent). The Bible's ink is the Designer's option 1 (Lapis), the default
// until the owner picks; the host's `APP_INKS` doesn't carry it yet, so the harness plays the host as it will be once it does.
// Run from the repo root with Node 24 (it reads web/src/theme/tokens.ts with type stripping):
//   node apps/bible/view/dev/make-tokens.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../../..');
const { THEMES } = await import(path.join(repo, 'web/src/theme/tokens.ts'));

const FONT_STACK = '"Inter Variable", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif';
const GROUPS = {
  surface: ['window', 'sunken', 'fill', 'fillStrong', 'overlay', 'scrim'],
  text: ['primary', 'secondary', 'tertiary', 'link', 'onAccent', 'disabled', 'danger'],
  glyph: ['default', 'soft', 'page'],
  accent: ['default', 'hover', 'pressed', 'subtle'],
  border: ['hairline', 'default', 'strong'],
  focus: ['ring'],
  status: ['online', 'warn', 'error'],
};
// The Designer's `design-drafts/bible-app/tokens.json`, `apps.bible.1` (Lapis).
const INK = {
  light: { window: '#FDFDFE', sidebar: '#F0F3F8', accent: '#2C51B6', accentHover: '#1F42A5', accentPressed: '#133395', accentSubtle: '#E0EAFE', onAccent: '#FFFFFF', link: '#2C51B6' },
  dusk: { window: '#414855', sidebar: '#39404E', accent: '#9FBDFE', accentHover: '#B2CAFE', accentPressed: '#90B0F4', accentSubtle: '#455577', onAccent: '#1B2029', link: '#B7CEFF' },
  dark: { window: '#22242A', sidebar: '#1B1D23', accent: '#759BF2', accentHover: '#86ACFF', accentPressed: '#668CE1', accentSubtle: '#273656', onAccent: '#14171B', link: '#81A8FF' },
};

const out = { _about: 'Generated by make-tokens.mjs: what the Desk app hands the Bible view, per theme, plus the harness page\'s own colors.' };
for (const theme of ['light', 'dusk', 'dark']) {
  const t = THEMES[theme];
  const v = { theme, font: FONT_STACK };
  for (const [group, keys] of Object.entries(GROUPS)) for (const k of keys) if (typeof t[group]?.[k] === 'string') v[`${group}.${k}`] = t[group][k];
  const ink = INK[theme];
  Object.assign(v, {
    'surface.window': ink.window, 'surface.sunken': ink.sidebar, 'accent.default': ink.accent, 'accent.hover': ink.accentHover,
    'accent.pressed': ink.accentPressed, 'accent.subtle': ink.accentSubtle, 'text.onAccent': ink.onAccent, 'text.link': ink.link,
    'focus.ring': ink.accent,
  });
  out[theme] = v;
  out[`harness.${theme}`] = { canvas: t.surface.worldBase, head: t.surface.window, border: t.border.default, text: t.text.primary, soft: t.text.tertiary };
}
fs.writeFileSync(path.join(here, 'tokens.json'), JSON.stringify(out, null, 1) + '\n');
console.log('wrote', path.join(here, 'tokens.json'));
